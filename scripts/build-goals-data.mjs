import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(rootDir, 'data-source/goals/goals.json');
const outputPath = resolve(rootDir, 'goals_data.js');
const dayStartHour = 4;

function formatLocalDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function getLogicalToday(now = new Date()) {
  return formatLocalDate(new Date(now.getTime() - dayStartHour * 60 * 60 * 1000));
}

function normalizeDate(value) {
  const text = String(value || '').trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text)) {
    return '';
  }

  const parsed = new Date(`${text}T00:00:00Z`);
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== text) {
    return '';
  }

  return text;
}

function normalizeDoneDates(done, startDate) {
  const seen = new Set();

  (Array.isArray(done) ? done : []).forEach((value) => {
    const date = normalizeDate(value);
    if (!date) {
      console.warn(`Skipped an invalid goal date: ${JSON.stringify(value)}`);
      return;
    }

    if (startDate && date < startDate) {
      console.warn(`Skipped ${date} because it is before the goal start date ${startDate}.`);
      return;
    }

    seen.add(date);
  });

  return [...seen].sort();
}

function normalizeGoal(goal, index) {
  const id = String(goal.id || '').trim();
  if (!id) {
    throw new Error(`Goal at position ${index} is missing an "id".`);
  }

  const title = String(goal.title || '').trim();
  if (!title) {
    throw new Error(`Goal "${id}" is missing a "title".`);
  }

  const startDate = normalizeDate(goal.startDate);
  if (!startDate) {
    throw new Error(`Goal "${id}" needs a "startDate" formatted as YYYY-MM-DD.`);
  }

  // Days before trackedFrom only count when they were actually recorded, so a
  // sparse backfill does not turn every unrecorded day into a missed day.
  const trackedFrom = normalizeDate(goal.trackedFrom) || startDate;
  if (trackedFrom < startDate) {
    throw new Error(`Goal "${id}" has a "trackedFrom" (${trackedFrom}) before its "startDate" (${startDate}).`);
  }

  return {
    id,
    title,
    context: String(goal.context || '').trim(),
    description: String(goal.description || '').trim(),
    cadence: String(goal.cadence || 'daily').trim() || 'daily',
    startDate,
    trackedFrom,
    active: goal.active !== false,
    done: normalizeDoneDates(goal.done, startDate),
  };
}

function readGoals() {
  return JSON.parse(readFileSync(sourcePath, 'utf8'));
}

function writeGoals(goals) {
  mkdirSync(dirname(sourcePath), { recursive: true });
  writeFileSync(sourcePath, `${JSON.stringify(goals, null, 2)}\n`, 'utf8');
}

export function buildGoalsData() {
  const goals = readGoals().map(normalizeGoal);
  const ids = new Set();

  goals.forEach((goal) => {
    if (ids.has(goal.id)) {
      throw new Error(`Duplicate goal id: ${goal.id}`);
    }

    ids.add(goal.id);
  });

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(
    outputPath,
    `// Generated by scripts/build-goals-data.mjs\nconst goals = ${JSON.stringify(goals, null, 2)};\nconst goalsDayStartHour = ${dayStartHour};\n`,
    'utf8'
  );

  return goals;
}

function parseArgs(argv) {
  let markDone = '';
  let markUndone = '';
  let date = '';

  argv.forEach((arg, index) => {
    if (arg === '--done' && argv[index + 1]) {
      markDone = argv[index + 1];
      return;
    }

    if (arg.startsWith('--done=')) {
      markDone = arg.slice('--done='.length);
      return;
    }

    if (arg === '--undo' && argv[index + 1]) {
      markUndone = argv[index + 1];
      return;
    }

    if (arg.startsWith('--undo=')) {
      markUndone = arg.slice('--undo='.length);
      return;
    }

    if (arg === '--date' && argv[index + 1]) {
      date = argv[index + 1];
      return;
    }

    if (arg.startsWith('--date=')) {
      date = arg.slice('--date='.length);
    }
  });

  return { markDone, markUndone, date };
}

function toggleGoalDate(goalId, targetDate, shouldBeDone) {
  const goals = readGoals();
  const goal = goals.find((entry) => String(entry.id || '').trim() === goalId);

  if (!goal) {
    throw new Error(`No goal with id "${goalId}" in ${sourcePath}`);
  }

  const startDate = normalizeDate(goal.startDate);
  if (shouldBeDone && startDate && targetDate < startDate) {
    throw new Error(`${targetDate} is before the start date for "${goalId}" (${startDate}).`);
  }

  const done = new Set(normalizeDoneDates(goal.done, startDate));
  const alreadyMatches = done.has(targetDate) === shouldBeDone;

  if (shouldBeDone) {
    done.add(targetDate);
  } else {
    done.delete(targetDate);
  }

  goal.done = [...done].sort();
  writeGoals(goals);

  if (alreadyMatches) {
    console.log(`${goalId} was already ${shouldBeDone ? 'marked done' : 'clear'} for ${targetDate}.`);
    return;
  }

  console.log(`${shouldBeDone ? 'Marked' : 'Cleared'} ${goalId} for ${targetDate}.`);
}

const isDirectRun = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isDirectRun) {
  try {
    const { markDone, markUndone, date } = parseArgs(process.argv.slice(2));
    const targetDate = date ? normalizeDate(date) : getLogicalToday();

    if ((markDone || markUndone) && !targetDate) {
      throw new Error(`Could not read "${date}" as a YYYY-MM-DD date.`);
    }

    if (markDone) {
      toggleGoalDate(markDone, targetDate, true);
    }

    if (markUndone) {
      toggleGoalDate(markUndone, targetDate, false);
    }

    buildGoalsData();
    console.log(`Wrote ${outputPath}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
